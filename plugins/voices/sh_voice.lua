-- Client side commands
if CLIENT then
    concommand.Add("impulse_hl2rp_printvcs", function(ply, cmd, args)
        if not args[1] then
            return print("Enter class as argument.")
        end

        if not impulse.Voice.List[args[1]] then
            return print("Class invalid.")
        end

        for k, _ in pairs(impulse.Voice.List[args[1]]) do
            print(k:upper())
        end
    end)

    netstream.Hook("voicePlay", function(sounds, volume, index)
        if index then
            local ply = Entity(index)
            if IsValid(ply) then
                ply:EmitQueuedSounds(sounds, nil, 0, volume)
            end
        else
            LocalPlayer():EmitQueuedSounds(sounds, nil, 0, volume)
        end
    end)
end

hook.Add("PlayerSay", "ImpulseVoiceAutoME", function(ply, text, teamChat)
    local lower = string.lower(text)  -- case-insensitive match

    -- Only trigger if the player says "haha"
    if lower ~= "haha" then
        return  -- normal chat
    end

    -- Get the player's voice classes
    local classes = impulse.Voice.GetClass(ply)
    for _, class in ipairs(classes) do
        local info = impulse.Voice.List[class.class]
        if not info then continue end

        for key, data in pairs(info) do
            if string.lower(key) == "haha" then
                -- Play sound for the player
                local source = data.source
                if type(source) == "table" then
                    source = table.Random(source)
                end
                ply:EmitSound(source)

                -- Run /me command automatically
                RunConsoleCommand("say", "/me " .. data.replacement)

                return "" -- prevent original chat message
            end
        end
    end
end)